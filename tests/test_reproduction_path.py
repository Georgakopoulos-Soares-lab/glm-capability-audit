"""Everything README.md tells a reader to run must exist and be committed.

Every file the reproduction commands touch was once present on the author's disk
and absent from git: a fresh clone could not have run any of them. Nothing in the
suite noticed, because the other tests run against the working tree. These run
against the index instead.

They are deliberately cheap. They do not execute the pipeline; they check that
its entry points would survive `git clone`, and that the directories the README
calls outputs are in fact not tracked.
"""
from __future__ import annotations

import pathlib
import re
import subprocess

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]

# the scripts README.md tells a reader to run
ENTRY_POINTS = [
    "pipelines/run.py",
    "scripts/common/download_data.py",
    "scripts/common/capacity_sweep.py",
    "scripts/track_b_viral/final_regime_table.py",
    "scripts/track_b_viral/hidden_homology_audit.py",
    "scripts/track_b_viral/nn_lookup_as_baseline.py",
    "analysis/bootstrap_corrected.py",
    "analysis/make_genus_concentration.py",
    "analysis/make_inference_provenance.py",
    "analysis/make_source_of_truth.py",
    "analysis/build_finalized_sot.py",
    "analysis/sot_path.py",
    "analysis/io_guards.py",
]

# written by the pipeline and by the analysis layer, never committed
OUTPUT_DIRS = ["results", "reports", "paper"]


def tracked() -> set[str]:
    def names(*args):
        out = subprocess.run(["git", "-C", str(REPO), *args],
                             capture_output=True, text=True, check=True)
        return set(out.stdout.split())
    # --diff-filter=d drops staged deletions: a path being removed from the
    # index is exactly what these tests want to see as untracked.
    return names("ls-files") | names("diff", "--cached", "--name-only",
                                     "--diff-filter=d")


@pytest.mark.parametrize("rel", ENTRY_POINTS)
def test_entry_point_exists(rel):
    assert (REPO / rel).exists(), f"{rel} is referenced by the reproduction path"


@pytest.mark.parametrize("rel", ENTRY_POINTS)
def test_entry_point_is_committed(rel):
    assert rel in tracked(), (
        f"{rel} exists on disk but git does not track it, so a fresh clone "
        f"cannot run the reproduction path")


@pytest.mark.parametrize("d", OUTPUT_DIRS)
def test_output_directory_is_not_tracked(d):
    """These are regenerated by the commands in README.md.

    They were tracked once, at 1,761 files and 18 MB, which made the repository
    a data archive wearing a codebase's directory layout.
    """
    leaked = sorted(p for p in tracked() if p.startswith(f"{d}/"))
    assert not leaked, f"{d}/ is an output directory but git tracks {leaked[:5]}"


def test_readme_commands_resolve():
    """Every `python <path>` the README prints must be a file in the repository."""
    text = (REPO / "README.md").read_text()
    cmds = re.findall(r"python3? ((?:pipelines|scripts|analysis)/[\w/]+\.py)", text)
    assert len(cmds) >= 10, f"only found {len(cmds)} commands; the regex has drifted"
    for rel in sorted(set(cmds)):
        assert (REPO / rel).exists(), f"README.md runs {rel}, which does not exist"


def test_readme_paths_resolve():
    """Backticked repository paths in the README must exist."""
    text = (REPO / "README.md").read_text()
    missing = []
    for ref in set(re.findall(r"`((?:pipelines|scripts|analysis|tests)/[\w/.]+)`", text)):
        p = REPO / ref.rstrip("/")
        if not p.exists():
            missing.append(ref)
    assert not missing, f"README.md names paths that do not exist: {sorted(missing)}"


def test_readme_stages_match_the_pipeline():
    """The stage table must list exactly the stages run.py accepts."""
    run = (REPO / "pipelines" / "run.py").read_text()
    declared = re.search(r"STAGES = \[(.*?)\]", run, re.S)
    assert declared, "run.py no longer declares STAGES"
    stages = set(re.findall(r'"(\w+)"', declared.group(1)))
    readme = (REPO / "README.md").read_text()
    table = readme.split("| Stage | What it does |", 1)
    assert len(table) == 2, "README.md no longer has a stage table"
    documented = set(re.findall(r"^\| `(\w+)` \|", table[1].split("\n\n", 1)[0], re.M))
    assert stages <= documented, f"undocumented stages: {sorted(stages - documented)}"
    assert documented <= stages, f"documented but not configured: {sorted(documented - stages)}"
