"""The reproduction path in README.md must exist, and must be committed.

Every file the four reproduction commands touch was present on the author's disk
and absent from git for several weeks: a fresh clone could not have run any of
them. Nothing in the test suite noticed, because the tests run against the working
tree. These tests run against the index instead.

They are deliberately cheap. They do not execute the pipeline; they check that the
pipeline's entry points, its frozen inputs and the figures the manuscript includes
would survive `git clone`.
"""
from __future__ import annotations

import pathlib
import re
import subprocess

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]

# the scripts README.md tells a reader to run, in order
ENTRY_POINTS = [
    "analysis/bootstrap_corrected.py",
    "analysis/build_finalized_sot.py",
    "analysis/make_selection_artifact.py",
    "analysis/make_fit_counts.py",
    "analysis/seed_expansion/regen_symmetric.py",
    "scripts/track_b_viral/unassigned_clustering_sensitivity.py",
    "paper/figures/build_paper.py",
    "paper/figures/audit_consistency.py",
]

# frozen inputs the generators read and cannot recompute
FROZEN_INPUTS = [
    "reports/tables/final_source_of_truth.csv",
    "reports/tables/final_source_of_truth_finalized.csv",
    "reports/tables/selection_3seed.csv",
    "reports/tables/fit_counts.csv",
    "reports/finalization/bootstrap_corrected.csv",
    "reports/finalization/bootstrap_3seed.csv",
    "reports/finalization/symmetric_regenerated.csv",
    "reports/layered/unassigned_sensitivity.json",
]


def tracked() -> set[str]:
    out = subprocess.run(["git", "-C", str(REPO), "ls-files"],
                         capture_output=True, text=True, check=True)
    staged = subprocess.run(["git", "-C", str(REPO), "diff", "--cached", "--name-only"],
                            capture_output=True, text=True, check=True)
    return set(out.stdout.split()) | set(staged.stdout.split())


@pytest.mark.parametrize("rel", ENTRY_POINTS + FROZEN_INPUTS)
def test_reproduction_file_exists(rel):
    assert (REPO / rel).exists(), f"{rel} is referenced by the reproduction path"


@pytest.mark.parametrize("rel", ENTRY_POINTS + FROZEN_INPUTS)
def test_reproduction_file_is_committed(rel):
    assert rel in tracked(), (
        f"{rel} exists on disk but git does not track it, so a fresh clone "
        f"cannot run the reproduction path")


def test_manuscript_figures_are_committed():
    """main.tex includes figures without an extension, so LaTeX resolves the PDF.

    The PNGs are gitignored as on-screen proofs. If an \\includegraphics ever pins
    .png again, the document stops building from a clean clone.
    """
    tex = (REPO / "paper" / "main.tex").read_text()
    inc = re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex)
    assert inc, "main.tex includes no figures"
    t = tracked()
    for stem in inc:
        assert not stem.endswith(".png"), (
            f"{stem} pins .png, which .gitignore excludes from the repository")
        p = f"paper/{stem}.pdf" if not stem.endswith(".pdf") else f"paper/{stem}"
        assert p in t, f"{p} is included by main.tex but is not committed"


def test_supplement_has_five_tables_and_the_text_agrees():
    """The per-arm fit-count table was cut. Nothing may cite it, and the range
    sentence in Supplementary information must end at the last table that exists."""
    supp = (REPO / "paper" / "supplementary.tex").read_text()
    tex = (REPO / "paper" / "main.tex").read_text()
    labels = re.findall(r"\\label\{tab:([a-z]+)\}", supp)
    assert labels == ["selection", "allarms", "bootstrap", "source", "hidden"], labels
    assert "seedsd" not in supp and "seedsd" not in tex, "the cut table is cited again"
    cited = set(re.findall(r"\\ref\{tab:([a-z]+)\}", tex)) & set(labels)
    assert cited == set(labels), f"uncited supplementary tables: {set(labels) - cited}"
    rng = re.search(r"Supplementary Tables~\\ref\{tab:([a-z]+)\} to "
                    r"\\ref\{tab:([a-z]+)\}", tex)
    assert rng, "no 'Supplementary Tables X to Y' sentence"
    assert (rng.group(1), rng.group(2)) == (labels[0], labels[-1])


def test_supplement_is_generated_not_handwritten():
    """supplementary.tex must stay machine-written.

    It was hand-corrected once, the generator was rerun, and the corrections were
    lost. The corrections now live in the generator; this keeps the banner that
    says so.
    """
    head = (REPO / "paper" / "supplementary.tex").read_text()[:400]
    assert "Generated by paper/figures/make_supplement_v2.py" in head
    assert "Do not edit by hand" in head
