#!/usr/bin/env python
"""Claim ledger: every main-text claim -> source file -> numbers -> permitted wording.

This is the document a reviewer, or a future co-author, uses to check that a sentence
in the manuscript is licensed by an analysis. It is generated, so it cannot drift.
"""
import json, os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
T, R = os.path.join(REPO, "reports", "tables"), os.path.join(REPO, "reports", "layered")


def main():
    from sot_path import sot_csv
    df = pd.read_csv(sot_csv())
    pool = json.load(open(f"{T}/translated_effect_pooled.json"))
    inter = json.load(open(f"{R}/regime_interaction.json"))
    sens = json.load(open(f"{R}/unassigned_sensitivity.json"))
    d = df[~df.skipped].set_index(["benchmark", "regime"])
    g = lambda b, r, c: d.loc[(b, r), c]
    qmin = min(x["q"] for v in inter.values() for x in v)

    L = ["# Claim ledger", "",
         "Generated by `paper/figures/make_claim_ledger.py`. Every main-text claim, the",
         "file that licenses it, the numbers, and the wording that is permitted.", ""]
    def claim(n, text, src, nums, permitted, forbidden=None):
        L.append(f"## C{n}. {text}")
        L.append(f"- **source** `{src}`")
        L.append(f"- **numbers** {nums}")
        L.append(f"- **permitted** {permitted}")
        if forbidden:
            L.append(f"- **FORBIDDEN** {forbidden}")
        L.append("")

    claim(1, "Fragment-level incremental performance at L0 is heterogeneous",
          "reports/tables/final_source_of_truth.csv",
          "excess ranges "
          f"{d.xs('L0', level='regime').excess.min():+.3f} to "
          f"{d.xs('L0', level='regime').excess.max():+.3f} MCC across nine benchmarks",
          "\"On published benchmark fragments, incremental gLM performance is "
          "heterogeneous, with excesses ranging from -0.059 to +0.107 MCC.\"",
          "any statistical winner tally; the 3/3/3 split is a point-estimate summary only")

    l1 = d.xs("L1", level="regime")
    big = l1[l1.n_rows >= 100].sort_values("excess", ascending=False)
    claim(2, "All four adequately populated L1 subsets favour the gLM",
          "reports/tables/final_source_of_truth.csv",
          ", ".join(f"{b} {r.excess:+.3f} (n={int(r.n_rows):,})" for b, r in big.iterrows()),
          "\"Across the four L1 populations retaining substantial evaluation samples, the "
          "gLM had the higher fragment-level point estimate, with excesses of +0.120 to "
          "+0.320 MCC.\"",
          "\"6 of 7\"; three L1 populations hold only 41 to 55 fragments")

    b, r = "HT hard_70", "L1"
    scen = [s for s in sens if s["regime"] == "L1"]
    claim(3, "HT hard_70 L1 is the one difference resolved under both estimands",
          "reports/tables/final_source_of_truth.csv, reports/layered/unassigned_sensitivity.json",
          f"excess {g(b,r,'excess'):+.3f}, fragment [{g(b,r,'frag_lo'):+.3f},"
          f"{g(b,r,'frag_hi'):+.3f}], source [{g(b,r,'src_lo'):+.3f},{g(b,r,'src_hi'):+.3f}], "
          f"coverage {100*g(b,r,'assign_cover'):.0f}%, sensitivity SUPERIOR in "
          f"{sum(s['verdict']=='SUPERIOR' for s in scen)}/{len(scen)} scenarios",
          "\"HViLM exceeded the baseline envelope by 0.194 MCC on nucleotide-divergent "
          "HT hard_70 fragments. The difference resolved under both fragment resampling "
          "and recovered-source resampling and remained positive across the prespecified "
          "hidden-dependence sensitivity analyses.\"",
          "any unrestricted novel-virus or general-capability claim")

    chg = d[(d.frag_verdict.isin(["SUPERIOR", "INFERIOR", "EQUIVALENT"]))
            & (~d.src_verdict.isin(["SUPERIOR", "INFERIOR", "EQUIVALENT"]))
            & (d.src_verdict != "unavailable")]
    claim(4, "Several fragment-resolved differences do not resolve across sources",
          "reports/tables/final_source_of_truth.csv",
          f"{len(chg)} cells change: " + ", ".join(
              f"{b} {r} ({d.loc[(b,r),'excess']:+.3f}, {d.loc[(b,r),'frag_verdict']} -> "
              f"{d.loc[(b,r),'src_verdict']})" for b, r in chg.index),
          "\"Fragment-level benchmark performance and uncertainty across biological "
          "sources are different inferential quantities.\"",
          "\"prior studies are statistically invalid\"; the point estimates are unchanged")

    claim(5, "Nucleotide divergence does not establish evolutionary independence",
          "reports/tables/final_source_of_truth.csv",
          "translated search removes 65.1% (HT std_95) to 97.0% (GUE phage) of L1",
          "\"A six frame translated search finds a detectable training relationship in "
          "65 to 97 percent of nucleotide-divergent fragments.\"",
          "\"translated leakage\" unless describing genuine train/test leakage")

    claim(6, "No consistent evidence that translated relatedness explains performance",
          "reports/tables/translated_effect_pooled.json, translated_effect_cells.csv",
          f"pooled gap {pool['pooled_gap']:+.3f} [{pool['pooled_lo']:+.3f},"
          f"{pool['pooled_hi']:+.3f}], positive in {pool['n_positive']}/{pool['n_cells']} "
          f"cells, sign test p={pool['sign_p']}",
          "\"We find no consistent evidence that detectable translated relatedness itself "
          "explains gLM performance.\"",
          "\"translated homology causes the win\"; \"translated relatedness has no effect\"")

    claim(7, "No L0 to L1 interaction survives multiplicity correction",
          "reports/layered/regime_interaction.json",
          f"10 tests across two envelopes, smallest BH q = {qmin:.3f}",
          "\"The fragment-level point-estimate pattern differs between L0 and L1, but "
          "direct interaction tests do not establish a systematic increase in incremental "
          "gLM value.\"",
          "\"excess grows under filtering\"; \"filtering reveals the advantage\"; \"D = 0\"")

    l2 = d.xs("L2", level="regime")
    claim(8, "L2 is unresolved everywhere",
          "reports/tables/final_source_of_truth.csv",
          ", ".join(f"{b} {r.excess:+.3f} (n={int(r.n_rows):,})" for b, r in l2.iterrows())
          + "; every interval spans zero",
          "\"Whether the incremental gLM value observed at L1 persists once detectable "
          "translated relatives are unavailable remains unresolved.\"",
          "\"the advantage disappears\"; \"the advantage persists\"; \"models fail at L2\"")

    ht = d.loc[("HT hard_70", "L2")]
    claim(9, "Large fragment counts do not imply broad biological support",
          "reports/tables/final_source_of_truth.csv (genus columns)",
          f"HT hard_70 L2: {int(ht.n_rows):,} fragments, {int(ht.positives)} positives, "
          f"{int(ht.positives_with_genus)} assigned ({100*ht.genus_cover:.1f}%), "
          f"{int(ht.n_positive_genera)} genera, largest {100*ht.top_genus_share:.1f}%",
          "\"Statistical adequacy and biological breadth are separate axes.\"",
          "characterising GUE phage L2 breadth (17/34 positives assigned) or "
          "Transm hard L1 concentration (2/14 assigned)")

    claim(10, "Model and hyperparameter selection used no test-set information",
          "reports/tables/final_source_of_truth.csv (dev_mcc column)",
          "model identity and learning rate both chosen on dev MCC, held fixed across "
          "L0/L1/L2; symmetric best-gLM-vs-best-baseline sensitivity agrees on every cell",
          "\"the model was selected on development performance and held fixed across "
          "regimes\"",
          "reporting a test-selected leading model")

    out = os.path.join(REPO, "reports", "CLAIM_LEDGER.md")
    open(out, "w").write("\n".join(L))
    print(f"wrote {out}   10 claims")


if __name__ == "__main__":
    main()
